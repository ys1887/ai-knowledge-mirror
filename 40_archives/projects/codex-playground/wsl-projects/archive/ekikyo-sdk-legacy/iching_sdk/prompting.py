from __future__ import annotations

from typing import Any

from iching_sdk.config import ValidationRuntimeError, repo_root
from iching_sdk.validation import read_input_text


EXTRACT_MARKER = "[MODE:EXTRACT]"
EXTRACT_COMPLEX_MARKER = "[TEMPLATE:EX_5]"
EXTRACT_COMPARE_MARKER = "[TEMPLATE:EX_COMPARE]"
EXTRACT_AUX_PREFIXES = ("之卦：", "互卦：", "錯卦：", "綜卦：")


def load_prompt_fragment(name: str) -> str:
    prompt_path = repo_root() / "prompts" / "fragments" / name
    if not prompt_path.is_file():
        raise ValidationRuntimeError(f"prompt fragment not found: {prompt_path}")
    return prompt_path.read_text(encoding="utf-8").strip()


def detect_mode(text: str) -> str:
    if EXTRACT_MARKER in text:
        return "extract"
    return "general"


def resolve_prompt_mode(input_text: str, override_mode: str | None) -> str:
    if override_mode:
        return override_mode
    return detect_mode(input_text)


def has_extract_auxiliary_hexagrams(input_text: str) -> bool:
    if EXTRACT_COMPLEX_MARKER not in input_text:
        return False
    for line in input_text.splitlines():
        for prefix in EXTRACT_AUX_PREFIXES:
            if line.startswith(prefix) and line.split("：", 1)[1].strip():
                return True
    return False


def is_extract_compare(input_text: str) -> bool:
    return EXTRACT_COMPARE_MARKER in input_text


def format_selected_sources(selection: dict[str, Any] | None) -> list[str]:
    if not selection:
        return []
    sections = ["## Selected Sources"]
    for group in selection.get("selected_groups", []):
        sections.append(f"- {group['group']}:")
        files = group.get("files", [])
        if not files:
            sections.append("  (none)")
            continue
        sections.extend([f"  - {path}" for path in files])
    selected_count = selection.get("selected_file_count")
    if selected_count is not None:
        sections.extend(["", f"Selected file count: {selected_count}"])
    return sections


def load_prompt_sections(input_text: str, mode: str) -> list[str]:
    if mode == "extract":
        sections = [load_prompt_fragment("extract_shared.md")]
        if is_extract_compare(input_text):
            sections.append(load_prompt_fragment("extract_compare.md"))
            return sections
        sections.append(load_prompt_fragment("extract_standard.md"))
        if has_extract_auxiliary_hexagrams(input_text):
            sections.append(load_prompt_fragment("extract_auxiliary.md"))
        return sections
    return [load_prompt_fragment("general.md")]


def build_prompt_text(
    input_text: str,
    mode: str,
    input_label: str,
    selection: dict[str, Any] | None = None,
) -> str:
    prompt_sections = load_prompt_sections(input_text, mode)
    project_root = repo_root()
    mode_notice = f"[MODE:{mode.upper()}]"

    sections = [
        "# ekikyo-sdk execution prompt",
        "## Runtime Context",
        f"- Runtime project: {project_root}",
        f"- CLI entry: {project_root / 'iching'}",
        f"- Sources root: {project_root / 'sources'}",
        f"- Rules root: {project_root / 'rules'}",
        f"- Prompts root: {project_root / 'prompts'}",
        f"- Input source: {input_label}",
        f"- Resolved mode: {mode}",
        "- Use only local Markdown files under sources/ as evidence unless the user explicitly asks otherwise.",
        "- The local CLI can be used for index lookup and validation.",
        "- This prompt is generated by ekikyo-sdk; keep durable workflow logic in the SDK project.",
        "",
        "## Mode Override",
        mode_notice,
    ]

    selected_sections = format_selected_sources(selection)
    if selected_sections:
        sections.extend(["", *selected_sections])

    sections.extend(
        [
            "",
            "## Prompt Instructions",
            "\n\n".join(prompt_sections),
            "",
            "## User Input",
            input_text.rstrip(),
            "",
        ]
    )
    return "\n".join(sections)


def load_prompt_input(input_arg: str) -> tuple[str, str]:
    return read_input_text(input_arg)
